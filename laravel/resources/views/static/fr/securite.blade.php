        <h1>Conseils de sécurité avant de verser le moindre dinar</h1>

        <p>
            {{ __('brand.name') }} est une plateforme de publication d'annonces uniquement, et
            n'est partie à aucune transaction. L'annonceur est responsable de son annonce ;
            nous n'intervenons pas dans le paiement et ne garantissons aucun bien. Ces
            conseils vous protègent de la plupart des arnaques connues sur le marché.
        </p>

        <h2>Ne payez pas avant d'avoir vu le bien de vos propres yeux</h2>
        <p>
            L'arnaque la plus répandue : de belles photos, un prix sous celui du marché, puis
            une demande d'« avance » ou d'« arrhes » pour réserver le bien avant la visite. Un
            bien réel n'a pas besoin d'une avance avant que vous ne le visitiez.
        </p>

        <h2>Vérifiez les documents</h2>
        <ul>
            <li>
                Demandez l'acte notarié ou le livret foncier, et assurez-vous que le nom qui
                y figure est bien celui du vendeur.
            </li>
            <li>
                Bien relevant d'un programme AADL, LSP ou social : sa revente est légalement
                restreinte pendant une durée déterminée.
            </li>
            <li>
                Ne signez aucun papier que vous n'avez pas compris, et l'acte se passe chez un
                notaire, pas au café.
            </li>
        </ul>

        <h2>Méfiez-vous du paiement à distance</h2>
        <p>
            N'envoyez pas d'argent par mandat postal ou BaridiMob à quelqu'un que vous n'avez
            pas rencontré. N'envoyez ni photo de votre pièce d'identité ni code de transfert à
            quiconque vous les demande dans une conversation.
        </p>

        <h2>Rencontrez-vous dans un lieu sûr</h2>
        <p>
            Visitez le bien en plein jour et accompagné. Si l'annonceur refuse la visite ou
            insiste sur la rapidité et la discrétion, c'est un signal suffisant pour vous
            arrêter.
        </p>

        <h2>Signalez toute annonce suspecte</h2>
        <p>
            Si vous voyez une fausse annonce, un prix illogique ou une demande de paiement
            anticipé, signalez-la pour que nous la retirions avant que quelqu'un d'autre ne
            tombe dedans.
        </p>
    </article>
