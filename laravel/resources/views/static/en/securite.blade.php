        </p>

        <h2>Don't pay before you have seen the property with your own eyes</h2>
        <p>
            The most common scam: attractive photos, a price below the market, then a request
            for a "deposit" or "down payment" to reserve the property before a viewing. A real
            property does not need a deposit before you visit it.
        </p>

        <h2>Check the paperwork</h2>
        <ul>
            <li>
                Ask for the notarised deed or the land register book, and make sure the name
                on it is the seller's.
            </li>
            <li>
                A property under an AADL, LSP or social housing programme: reselling it is
                legally restricted for a set period.
            </li>
            <li>
                Don't sign anything you have not understood, and the deed is executed at a
                notary's office, not in a café.
            </li>
        </ul>

        <h2>Beware of paying remotely</h2>
        <p>
            Don't send money by postal transfer or BaridiMob to someone you have not met. And
            don't send a photo of your ID card or a transfer code to anyone who asks for it in
            a chat.
        </p>

        <h2>Meet somewhere safe</h2>
        <p>
            Visit the property in daylight and with someone else. If the advertiser refuses a
            viewing, or presses for speed and secrecy, that is signal enough to stop.
        </p>

        <h2>Report any suspicious ad</h2>
        <p>
            If you see a fake ad, an illogical price or a request for advance payment, report
            it so we can take it down before someone else falls for it.
        </p>
