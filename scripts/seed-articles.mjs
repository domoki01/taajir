for (const article of kArticles) {
  const blocks = parseBody(article.body);
  const existing = await db
    .collection("articles")
    .where("slug", "==", article.slug)
    .limit(1)
    .get();

  const ref = existing.empty
    ? db.collection("articles").doc()
    : existing.docs[0].ref;
  const prior = existing.empty ? null : existing.docs[0].data();

  await ref.set(
    {
      slug: article.slug,
      title: article.title,
      excerpt: article.excerpt,
      body: blocks,
      coverUrl: article.coverUrl,
      coverAlt: article.coverAlt,
      authorUid: prior?.authorUid ?? "system",
      authorName: prior?.authorName ?? "فريق تأجير",
      status: "published",
      tags: article.tags,
      readMinutes: readingMinutes(blocks),
      // Kept if it is already out: republishing a corrected typo must not move
      // the piece to the top of the list or change its dateline.
      publishedAt: prior?.publishedAt ?? now,
      createdAt: prior?.createdAt ?? now,
      updatedAt: now,
      commentCount: prior?.commentCount ?? 0,
    },
    { merge: true },
  );

  if (existing.empty) created++;
  else updated++;
  console.log(
    `${existing.empty ? "created" : "updated"} — /articles/${article.slug} (${blocks.length} blocks, ${readingMinutes(blocks)} min)`,
  );
}

console.log(`\n${created} created, ${updated} updated.`);
