        <h2>L'idée</h2>
        <p>
            Chercher un logement en Algérie passe le plus souvent par des groupes
            dispersés et des annonces sans prix, sans localisation précise et sans
            information sur les documents. Notre objectif est une annonce claire : le
            prix, la commune, la surface, le nombre de pièces et l'état des papiers —
            avant même de décrocher le téléphone.
        </p>

        <h2>Gratuit pour les particuliers</h2>
        <p>
            La publication est gratuite pour les particuliers. Les agences immobilières
            souscrivent à des forfaits qui leur donnent un quota d'annonces plus élevé,
            une mise en avant de leurs annonces et un badge de vérification lié à leur
            agrément officiel.
        </p>

        <h2>Ce que nous ne sommes pas</h2>
        <p>
            Nous ne sommes ni une agence immobilière ni un intermédiaire de vente. Nous
            ne percevons aucune commission sur une transaction et n'intervenons pas dans
            le paiement entre l'annonceur et le client. La responsabilité du contenu
            d'une annonce revient à son auteur.
        </p>
