/** Same three prefixes the editor uses. Kept in step with src/lib/article.ts. */
function parseBody(raw) {
  const blocks = [];
  for (const line of raw.split(/\r?\n/)) {
    const text = line.trim();
    if (!text) continue;
    if (text.startsWith("## "))
      blocks.push({ type: "h2", text: text.slice(3).trim() });
    else if (text.startsWith("- "))
      blocks.push({ type: "li", text: text.slice(2).trim() });
    else if (text.startsWith("> "))
      blocks.push({ type: "quote", text: text.slice(2).trim() });
    else blocks.push({ type: "p", text });
  }
  return blocks;
}

function readingMinutes(blocks) {
  const words = blocks
    .map((b) => b.text.split(/\s+/).length)
    .reduce((a, b) => a + b, 0);
  return Math.max(1, Math.ceil(words / 180));
}

