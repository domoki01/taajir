            <li>Biens que l'annonceur n'a pas le droit de proposer.</li>
            <li>Demande d'avance ou d'arrhes avant la visite du bien.</li>
            <li>Tout contenu contraire à la loi algérienne.</li>
        </ul>

        <h2>4. Agences immobilières</h2>
        <p>
            L'exercice de l'intermédiation immobilière en Algérie est soumis à un agrément
            officiel conformément au décret exécutif 09-18 et à ses modifications. Le badge
            « vérifié » n'est attribué qu'aux agences ayant fourni leur numéro d'agrément et
            leur carte professionnelle, et ne constitue aucune garantie de la plateforme sur
            un bien.
        </p>

        <h2>5. Abonnements</h2>
        <p>
            Les forfaits payants donnent droit à un quota d'annonces et à des options de
            mise en avant pendant leur durée. Ils ne constituent aucune garantie de vente
            ou de location et ne sont pas remboursables après activation, sauf erreur
            imputable à la plateforme.
        </p>

